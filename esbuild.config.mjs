import esbuild from "esbuild";
import process from "process";
import builtins from "builtin-modules";
import { readFile } from "node:fs/promises";

const runtimeLicenses = await Promise.all([
	["pdf-lib", "node_modules/pdf-lib/LICENSE.md"],
	["@pdf-lib/standard-fonts", "node_modules/@pdf-lib/standard-fonts/LICENSE.md"],
	["@pdf-lib/upng", "node_modules/@pdf-lib/upng/LICENSE"],
	["pako", "node_modules/pako/LICENSE"],
].map(async ([name, file]) => `${name}\n${await readFile(new URL(file, import.meta.url), "utf8")}`));
const zlibSource = await readFile(new URL("node_modules/pako/lib/zlib/inflate.js", import.meta.url), "utf8");
runtimeLicenses.push("pako (zlib)\n" + zlibSource.match(/^\/\/.*(?:\n\/\/.*)*/m)[0].replace(/^\/\/ ?/gm, ""));

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
If you want to view the source, please visit the github repository of this plugin.
*/
` + `\n/*! Bundled dependency licenses\n\n${runtimeLicenses.join("\n\n")}\n*/\n`;

const prod = process.argv[2] === "production";

const context = await esbuild.context({
	banner: { js: banner },
	entryPoints: ["src/main.ts"],
	bundle: true,
	external: [
		"obsidian",
		"electron",
		"@codemirror/autocomplete",
		"@codemirror/collab",
		"@codemirror/commands",
		"@codemirror/language",
		"@codemirror/lint",
		"@codemirror/search",
		"@codemirror/state",
		"@codemirror/view",
		"@lezer/common",
		"@lezer/highlight",
		"@lezer/lr",
		...builtins,
	],
	format: "cjs",
	target: "es2020",
	logLevel: "info",
	sourcemap: prod ? false : "inline",
	treeShaking: true,
	outfile: "main.js",
});

if (prod) {
	await context.rebuild();
	await context.dispose();
} else {
	await context.watch();
}
